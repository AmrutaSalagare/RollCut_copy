# -*- coding: utf-8 -*-
from solver_v2 import load_models, solve, print_plan

gen_model, _, pool_feats, _, _ = load_models()

def get_int(prompt, min_val=1):
    while True:
        try:
            v = int(input(prompt).strip())
            if v >= min_val: return v
            print("  Must be >= " + str(min_val) + ". Try again.")
        except ValueError:
            print("  Invalid number. Try again.")

def get_roll_widths():
    print("\nEnter available roll widths (comma-separated, e.g. 3000,2500,2800):")
    while True:
        raw = input("  Roll widths: ").strip()
        try:
            widths = [int(x.strip()) for x in raw.split(",") if x.strip()]
            if widths: return widths
        except ValueError:
            pass
        print("  Invalid input. Try again.")

def get_orders():
    print("\nEnter customer orders (width in mm and quantity).")
    print("  Type 'done' when finished.\n")
    orders = {}
    while True:
        raw = input("  Width (mm) [or 'done']: ").strip().lower()
        if raw == "done":
            if not orders:
                print("  Add at least one order first.")
                continue
            break
        try:
            width = int(raw)
            if width <= 0: raise ValueError
        except ValueError:
            print("  Invalid width. Enter a positive integer.")
            continue
        qty = get_int("  Quantity        : ")
        orders[width] = orders.get(width, 0) + qty
        print("  Added: " + str(width) + "mm x" + str(qty) +
              "  (total qty for this width: " + str(orders[width]) + ")")
    return list(orders.items())

def run():
    # print("=" * 58)
    # print("   1D ROLL CUTTING OPTIMIZER")
    # print("   Combinations generated by ML, ranked by actual waste")
    # print("=" * 58)

    while True:
        rolls  = get_roll_widths()
        orders = get_orders()

        total_mm = sum(w * q for w, q in orders)
        print("\n  Total material needed: " + str(total_mm) + "mm")
        # print("  Solving with ML...")
        plan = solve(rolls, orders, gen_model, pool_feats)
        print_plan(plan)

        again = input("\nRun another scenario? (y/n): ").strip().lower()
        if again != "y":
            # print("\nGoodbye.")
            break

if __name__ == "__main__":
    run()
